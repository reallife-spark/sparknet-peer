#!/usr/bin/env python3
"""MASTERSPIKE — the llm-wiki format as an inference artifact (peer PLAN Step 7).

Two backends, one source: the Ollama ``Modelfile`` and the vLLM system-prompt
artifact are both generated from ``.opencode/skills/llm-wiki/SKILL.md``, so
switching inference backends cannot silently drop the format (DoD 2).

* ``generate`` writes both committed artifacts (DoD 1/2).
* ``verify`` regenerates both in memory and fails on any divergence from the
  committed files — a committed artifact edited by hand, a Modelfile rebuilt
  against a different base, or a source skill that moved, expands, is
  re-formatted, or disappears all fail verification (DoD 3).

The model carries a *format*, never a capability (DoD 4): the artifacts are
text — no key, no signer socket, no state dir — and authority stays Ed25519 in
the Master, not in a prompt. This script performs no network access and never
invokes Ollama.
"""

from __future__ import annotations

import argparse
import hashlib
import itertools
import sys
from pathlib import Path

TEMPERATURE = "0.1"
BASE_MODEL_DEFAULT = "llama3.2"
MODEL_NAME = "sparknet-masterspike"
SOURCE_REL = Path(".opencode") / "skills" / "llm-wiki" / "SKILL.md"
OUT_REL = Path("peer-node") / "manifests" / "masterspike"
GENERATOR_TAG = "peer-node/scripts/sparknet-masterspike.py"

SELECTABLE_AGENTS_BEFORE = ["plan", "build", "vault", "node-orchestrator"]


def _default_fabric_root() -> Path:
    return Path(__file__).resolve().parent.parent.parent


def _source(root: Path) -> Path:
    return root / SOURCE_REL


def extract_format(source_bytes: bytes) -> str:
    """The skill's body: frontmatter stripped, line endings normalised,
    surrounding blank lines trimmed, exactly one trailing newline."""
    text = source_bytes.decode("utf-8")
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            text = text[end + 4 :]
    text = "\n".join(line.rstrip() for line in text.replace("\r\n", "\n").split("\n"))
    return text.strip() + "\n"


def _provenance_headers(root: Path, name: str, source_sha256: str) -> str:
    return (
        f"# sparknet MASTERSPIKE — GENERATED by {GENERATOR_TAG}; do not edit by hand.\n"
        f"# source: {SOURCE_REL}\n"
        f"# source-sha256: {source_sha256}\n"
        f"# artifact: {name}\n"
    )


def render_ollama(root: Path, source_sha256: str, body: str, base: str) -> str:
    headers = _provenance_headers(root, "Modelfile", source_sha256)
    return f'{headers}# backend: ollama\nFROM {base}\nPARAMETER temperature {TEMPERATURE}\nSYSTEM """\n{body}"""\n'


def render_vllm(root: Path, source_sha256: str, body: str) -> str:
    headers = _provenance_headers(root, "vllm-system-prompt.md", source_sha256)
    return (
        f"{headers}"
        f"# backend: vllm\n"
        f"# temperature: {TEMPERATURE}\n"
        f"# usage: pass the body below as the system prompt to a vLLM OpenAI-compatible\n"
        f"# server (application-side system message, or wrapped in a chat template). It is\n"
        f"# byte-identical to the Ollama Modelfile's SYSTEM block, so the format cannot\n"
        f"# silently drop when the inference backend switches.\n"
        f"\n"
        f"{body}"
    )


def render_all(root: Path, base: str) -> dict[str, str]:
    source_path = _source(root)
    if not source_path.is_file():
        sys.exit(f"model-verify: source skill missing: {source_path} (run `make wiki-sync` to vendor it)")
    raw = source_path.read_bytes()
    source_sha256 = hashlib.sha256(raw).hexdigest()
    body = extract_format(raw)
    return {
        "Modelfile": render_ollama(root, source_sha256, body, base),
        "vllm-system-prompt.md": render_vllm(root, source_sha256, body),
    }


def out_dir(root: Path) -> Path:
    return root / OUT_REL


def _write_committed(root: Path, artifacts: dict[str, str]) -> None:
    directory = out_dir(root)
    directory.mkdir(parents=True, exist_ok=True)
    for name, content in artifacts.items():
        (directory / name).write_text(content)


def _read_committed(root: Path) -> dict[str, str]:
    committed: dict[str, str] = {}
    for name in ("Modelfile", "vllm-system-prompt.md"):
        path = out_dir(root) / name
        if not path.is_file():
            sys.exit(f"model-verify: committed artifact missing: {path} (run `make model-generate`)")
        committed[name] = path.read_text()
    return committed


def cmd_generate(root: Path, base: str) -> None:
    artifacts = render_all(root, base)
    _write_committed(root, artifacts)
    raw = _source(root).read_bytes()
    print(
        f"model-generate: wrote MASTERSPIKE artifacts to {out_dir(root)} "
        f"(temperature {TEMPERATURE}, base {base}, source {SOURCE_REL} sha256 {hashlib.sha256(raw).hexdigest()})"
    )


def cmd_verify(root: Path, base: str) -> None:
    expected = render_all(root, base)
    failed = False
    for name, want in expected.items():
        path = out_dir(root) / name
        got = _read_committed(root).get(name)
        if got != want:
            failed = True
            sys.stderr.write(f"model-verify: divergence in {path}\n")
            got_lines = got.splitlines()
            want_lines = want.splitlines()
            for i, (a, b) in enumerate(itertools.zip_longest(got_lines, want_lines)):
                marker = " " if a == b else "!"
                sys.stderr.write(f"  line {i + 1} {marker} got={a!r} want={b!r}\n")
    if failed:
        sys.exit(
            "model-verify: FAILED — committed MASTERSPIKE artifacts diverge "
            "from their source; run `make model-generate`"
        )
    source_path = _source(root)
    source_sha256 = hashlib.sha256(source_path.read_bytes()).hexdigest()
    print(
        f"model-verify: ok — {len(expected)} artifact(s) match their source "
        f"({SOURCE_REL} sha256 {source_sha256}, temperature {TEMPERATURE})"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate or verify the committed MASTERSPIKE artifacts")
    parser.add_argument("command", choices=("generate", "verify"))
    parser.add_argument("--root", type=Path, default=None, help="fabric root (default: nearest to this script)")
    parser.add_argument("--base", default=BASE_MODEL_DEFAULT, help=f"Ollama base model (default {BASE_MODEL_DEFAULT})")
    args = parser.parse_args()

    root = Path(args.root or _default_fabric_root()).resolve()
    if args.command == "generate":
        cmd_generate(root, args.base)
    else:
        cmd_verify(root, args.base)
    return 0


if __name__ == "__main__":
    sys.exit(main())
