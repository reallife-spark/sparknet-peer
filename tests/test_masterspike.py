"""peer PLAN Step 7 — MASTERSPIKE: the llm-wiki format as an inference artifact.

DoD 1: an Ollama ``Modelfile`` inlines the llm-wiki knowledge format from
``.opencode/skills/llm-wiki/SKILL.md`` at ``temperature 0.1``, and
`make model-build` / `make model-serve` exist.
DoD 2: a vLLM equivalent prompt artifact is generated from the same source.
DoD 3: `make model-verify` fails if the two diverge or the source skill moves.
DoD 4: the model is selectable as an agent and holds no signing capability —
authority is Ed25519 in the Master, never a prompt.

Self-contained suite: it reads the real source skill and the committed
artifacts; the divergence/moved-source legs run against pytest ``tmp_path``
mirrors so the committed artifacts are never mutated.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROLE_ROOT = Path(__file__).resolve().parents[1]
FABRIC_ROOT = ROLE_ROOT.parent
SOURCE = FABRIC_ROOT / ".opencode" / "skills" / "llm-wiki" / "SKILL.md"
MASTERSPIKE = ROLE_ROOT / "manifests" / "masterspike"
MODELFILE = MASTERSPIKE / "Modelfile"
VLLM = MASTERSPIKE / "vllm-system-prompt.md"
GENERATOR = ROLE_ROOT / "scripts" / "sparknet-masterspike.py"
MAKEFILE = ROLE_ROOT / "Makefile"


def _extract_format(raw: bytes) -> str:
    """The skill body as the generator embeds it: frontmatter stripped, line
    endings normalised, surrounding blank lines trimmed, one trailing newline."""
    text = raw.decode("utf-8")
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            text = text[end + 4 :]
    text = "\n".join(line.rstrip() for line in text.replace("\r\n", "\n").split("\n"))
    return text.strip() + "\n"


def _source_sha256() -> str:
    return hashlib.sha256(SOURCE.read_bytes()).hexdigest()


def _modelfile_body() -> str:
    lines = MODELFILE.read_text().splitlines(keepends=True)
    open_idx = next(i for i, line in enumerate(lines) if line.startswith("SYSTEM ")) + 1
    close_idx = next(i for i, line in enumerate(lines[open_idx:], open_idx) if line.startswith('"""'))
    return "".join(lines[open_idx:close_idx])


def _vllm_body() -> str:
    lines = VLLM.read_text().splitlines()
    blank = next(i for i, line in enumerate(lines) if line == "")
    return "\n".join(lines[blank + 1 :]) + "\n"


# --- DoD 1: the Ollama Modelfile inlines the wiki format at temperature 0.1 ---


def test_the_modelfile_inlines_the_llm_wiki_format_at_temperature_0_1():
    text = MODELFILE.read_text()
    assert "PARAMETER temperature 0.1" in text, "the format carrier must answer at a stable, low temperature"
    assert any(line.startswith("FROM ") for line in text.splitlines()), "the Modelfile must declare a base model"
    assert _modelfile_body() == _extract_format(SOURCE.read_bytes()), (
        "the SYSTEM block must be the llm-wiki skill's body — nothing added, nothing dropped"
    )
    assert f"# source-sha256: {_source_sha256()}" in text, "the artifact must name the exact source revision"
    assert "generated by" in text.lower()


def test_make_exposes_build_and_serve_targets():
    text = MAKEFILE.read_text()
    for target in ("model-generate: ##", "model-verify: ##", "model-build: ##", "model-serve: ##"):
        assert target in text, f"Makefile must expose {target.split()[0]}"


# --- DoD 2: the vLLM artifact carries the same format from the same source -----


def test_the_vllm_artifact_carries_the_same_format_from_the_same_source():
    assert _vllm_body() == _extract_format(SOURCE.read_bytes()), (
        "the vLLM system prompt must embed the byte-identical format body"
    )
    assert _vllm_body() == _modelfile_body(), "the two backends must not be able to silently disagree"
    assert f"# source-sha256: {_source_sha256()}" in VLLM.read_text()


# --- DoD 3: `make model-verify` fails when the artifacts or the source move ---


def test_model_verify_passes_on_the_committed_tree():
    result = subprocess.run(["make", "-C", str(ROLE_ROOT), "model-verify"], capture_output=True, text=True)
    assert result.returncode == 0, result.stderr


def _mirror(tmp_path, *, corrupt: str | None = None, source_mutate: bool = False) -> Path:
    root = tmp_path
    (root / ".opencode" / "skills" / "llm-wiki").mkdir(parents=True)
    (root / "peer-node" / "manifests" / "masterspike").mkdir(parents=True)
    shutil.copy2(SOURCE, root / ".opencode" / "skills" / "llm-wiki" / "SKILL.md")
    shutil.copy2(MODELFILE, root / "peer-node" / "manifests" / "masterspike" / "Modelfile")
    shutil.copy2(VLLM, root / "peer-node" / "manifests" / "masterspike" / "vllm-system-prompt.md")
    if corrupt == "modelfile":
        path = root / "peer-node" / "manifests" / "masterspike" / "Modelfile"
        path.write_text(path.read_text() + "PARAMETER temperature 0.9\n")
    if corrupt == "vllm":
        path = root / "peer-node" / "manifests" / "masterspike" / "vllm-system-prompt.md"
        path.write_text(path.read_text() + "a hand-written line that belongs to no source\n")
    if corrupt == "remove-modelfile":
        (root / "peer-node" / "manifests" / "masterspike" / "Modelfile").unlink()
    if corrupt == "remove-source":
        (root / ".opencode" / "skills" / "llm-wiki" / "SKILL.md").unlink()
    if source_mutate:
        path = root / ".opencode" / "skills" / "llm-wiki" / "SKILL.md"
        path.write_text(path.read_text() + "\n# the source skill moved onwards after generation\n")
    return root


def test_model_verify_fails_when_the_artifacts_diverge(tmp_path):
    root = _mirror(tmp_path, corrupt="modelfile")
    result = subprocess.run(
        [sys.executable, str(GENERATOR), "verify", "--root", str(root)], capture_output=True, text=True
    )
    assert result.returncode != 0, "a diverged Modelfile must not verify"
    assert "divergence" in (result.stderr + result.stdout).lower()

    root = _mirror(tmp_path / "leg", corrupt="vllm")
    result = subprocess.run(
        [sys.executable, str(GENERATOR), "verify", "--root", str(root)], capture_output=True, text=True
    )
    assert result.returncode != 0, "a diverged vLLM artifact must not verify"


def test_model_verify_fails_when_the_source_skill_moves(tmp_path):
    root = _mirror(tmp_path, source_mutate=True)
    result = subprocess.run(
        [sys.executable, str(GENERATOR), "verify", "--root", str(root)], capture_output=True, text=True
    )
    assert result.returncode != 0, "a source skill that moved past generation must fail verification"


def test_model_verify_fails_when_the_source_disappears(tmp_path):
    root = _mirror(tmp_path, corrupt="remove-source")
    result = subprocess.run(
        [sys.executable, str(GENERATOR), "verify", "--root", str(root)], capture_output=True, text=True
    )
    assert result.returncode != 0
    assert "missing" in (result.stderr + result.stdout).lower()


def test_model_verify_fails_when_an_artifact_is_missing(tmp_path):
    root = _mirror(tmp_path, corrupt="remove-modelfile")
    result = subprocess.run(
        [sys.executable, str(GENERATOR), "verify", "--root", str(root)], capture_output=True, text=True
    )
    assert result.returncode != 0
    assert "missing" in (result.stderr + result.stdout).lower()


# --- DoD 4: selectable as an agent, but a format carrier, never a signer --------


def test_the_model_is_selectable_as_an_agent():
    agent_models = json.loads((ROLE_ROOT / "manifests" / "agent-models.json").read_text())
    entry = next(m for m in agent_models["selectable"] if m["id"] == "masterspike")
    assert entry["agent"] == "masterspike"
    assert entry.get("capabilities") == []

    compose = (ROLE_ROOT / "configs" / "ai-stack" / "docker-compose.yml").read_text()
    assert "masterspike" in compose
    assert 'MODEL_FILTER_LIST: "plan,build,vault,node-orchestrator,masterspike"' in compose

    stake = json.loads((ROLE_ROOT / "manifests" / "masterspike.json").read_text())
    assert stake["agent"]["selectable"] is True
    assert stake["schema"] == "sparknet-masterspike/1"
    assert stake["temperature"] == 0.1


def test_the_model_holds_no_signing_capability():
    stake = json.loads((ROLE_ROOT / "manifests" / "masterspike.json").read_text())
    boundary = stake["signing_boundary"]
    assert boundary["capability"] is None
    assert boundary["capabilities"] == []
    assert "sign" in boundary["explicitly_not_granted"]
    for artifact in (MODELFILE, VLLM):
        text = artifact.read_text()
        assert "-----BEGIN" not in text, "no PEM key block may ride along in an artifact"
        assert "PRIVATE KEY" not in text, "no key material may ride along in an artifact"
